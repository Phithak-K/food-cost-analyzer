import '../../../core/constants/app_constants.dart';
import '../../recipes/models/recipe.dart';

/// Represents a classified item in the Menu Engineering Matrix.
class MenuMatrixItem {
  final Recipe recipe;
  final int salesVolume; // Volume / Number of units sold
  final double contributionMargin; // Profit per dish (Selling Price - Food Cost)
  final MenuQuadrant categoryType; // Star, Plowhorse, Puzzle, Dog

  const MenuMatrixItem({
    required this.recipe,
    required this.salesVolume,
    required this.contributionMargin,
    required this.categoryType,
  });

  /// Alias for categoryType
  MenuQuadrant get quadrant => categoryType;

  /// Total Revenue generated by this menu item
  double get totalRevenue => recipe.sellingPrice * salesVolume;

  /// Total Food Cost incurred by this menu item
  double get totalFoodCost => recipe.totalCost * salesVolume;

  /// Total Gross Profit generated by this menu item
  double get totalProfit => contributionMargin * salesVolume;

  /// Food Cost %
  double get foodCostPercentage => recipe.foodCostPercentage;

  MenuMatrixItem copyWith({
    Recipe? recipe,
    int? salesVolume,
    double? contributionMargin,
    MenuQuadrant? categoryType,
  }) {
    return MenuMatrixItem(
      recipe: recipe ?? this.recipe,
      salesVolume: salesVolume ?? this.salesVolume,
      contributionMargin: contributionMargin ?? this.contributionMargin,
      categoryType: categoryType ?? this.categoryType,
    );
  }

  Map<String, dynamic> toJson() => {
        'recipe': recipe.toJson(),
        'salesVolume': salesVolume,
        'contributionMargin': contributionMargin,
        'categoryType': categoryType.name,
        'totalRevenue': totalRevenue,
        'totalProfit': totalProfit,
      };
}

/// Type alias for backward compatibility with existing code
typedef ClassifiedMenuItem = MenuMatrixItem;
